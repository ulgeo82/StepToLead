def spin(text: str, rnd: random.Random | None = None) -> str:
    rnd = rnd or random
    pattern = re.compile(r"\{([^{}]*)\}")
    while True:
        m = pattern.search(text)
        if not m:
            break
        text = text[:m.start()] + rnd.choice(m.group(1).split("|")) + text[m.end():]
    return re.sub(r"\s+", " ", text).strip()


def line(topic: str, turn: int, rnd: random.Random | None = None) -> str:
    rnd = rnd or random
    turns = TOPICS[topic]
    return spin(rnd.choice(turns[min(turn, len(turns) - 1)]), rnd)


def turns(topic: str) -> int:
    return len(TOPICS[topic])
