def code_for(place: str) -> int | None:
    key = norm(place).strip().replace("г.", "").strip()
    if not key:
        return None
    if key in CODES:
        return CODES[key]
    return next((code for name, code in CODES.items() if key.startswith(name) or name.startswith(key) and len(key) >= 4),
                None)


def codes_for(places: list[str]) -> tuple[list[int], list[str]]:
    """(коды регионов, места без кода). Пустой список мест — вся Россия."""
    codes, unknown = [], []
    for place in places or []:
        code = code_for(place)
        if code is None:
            unknown.append(place)
        elif code not in codes:
            codes.append(code)
    return codes, unknown
